#!/usr/bin/env python3
"""Draws the Encore mark, and writes it everywhere it is used.

The mark is a true circular "e": a ring split by a crossbar through its centre. The lower
arc runs to 45 degrees, then carries on straight along its own tangent (so the join is
seamless) into a right-angle arrowhead, one leg horizontal and one vertical, pointing up
and to the right. Everything hangs off the circle:
  - the circle's centre is the centre of the mark, so it sits centred in its box;
  - the arrow's legs are equal, and the vertical leg ends flush with the circle's bottom
    edge, so the mark's ink box is an exact square (R + stroke/2 on every side);
  - the gap between the crossbar and the arrow's horizontal leg is one stroke, as far as
    the weight allows: the arrow's right edge never passes the ring's, and at the heaviest
    weights it just clears the crossbar.

Outputs, from the one geometry:
  Resources/AppIcon.icon/Assets/mark.svg   the icon artwork, as strokes
  Resources/Assets.xcassets/*.symbolset    the menu bar symbols, as outlines at SF Symbols' weights

Run it after changing the mark, then ./build.sh and tools/export-icon-preview.sh.
"""
import json
import math
import pathlib
import sys

C = math.sqrt(0.5)       # cos 45 = sin 45


def geometry(ro, w):
    """The mark for an ink radius `ro` and stroke `w`, centred on the origin, y down."""
    r, h = ro - w / 2, w / 2
    arc = r * C                                  # where the circle reaches 45 deg
    # The arrow's corner height: one stroke of gap under the crossbar, but low enough that
    # its right edge stays inside the ring's (so the ink box stays square), and never
    # lower than the arc itself.
    ty = min(max(2 * w, 2 * arc + h - ro), arc)
    run = (arc - ty) / C                         # how far the arc carries on along its tangent
    return dict(r=r, h=h, ro=ro, ri=r - h, arc=arc, tx=arc + run * C, ty=ty, run=run,
                leg=ro - ty, xo=math.sqrt(ro * ro - h * h))


# ---- the app icon -----------------------------------------------------------------
INK = "#F8F3EA"          # cream, on the bordeaux field (see icon.json)
ICON_RO, ICON_STROKE = 280.0, 60.0   # ink radius and stroke, on the 1024 canvas


def icon_svg():
    g, f = geometry(ICON_RO, ICON_STROKE), "{:.2f}".format
    r, w = f(g["r"]), f(ICON_STROKE)
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">\n'
        '  <!-- Generated by tools/make-mark.py. The Encore mark: a circular "e" whose arc\n'
        '       ends in a right-angle arrowhead. -->\n'
        f'  <g transform="translate(512 512)" fill="none" stroke="{INK}" stroke-width="{w}" '
        'stroke-linejoin="miter">\n'
        f'    <path d="M-{r} 0A{r} {r} 0 0 1 {r} 0"/>\n'
        f'    <path fill="{INK}" stroke="none" d="M-{r} {f(-g["h"])}H{f(g["xo"])}'
        f'A{f(g["ro"])} {f(g["ro"])} 0 0 1 {f(g["xo"])} {f(g["h"])}H-{r}Z"/>\n'
        f'    <path d="M-{r} 0A{r} {r} 0 0 0 {f(g["arc"])} {f(g["arc"])}L{f(g["tx"])} {f(g["ty"])}"/>\n'
        f'    <path d="M{f(g["tx"] - g["leg"])} {f(g["ty"])}H{f(g["tx"])}V{f(g["ty"] + g["leg"])}"/>\n'
        '  </g>\n'
        '</svg>\n')


def outline(cx, cy, ro, w):
    """The mark as filled outlines, all wound the same way so they merge where they overlap."""
    g, f = geometry(ro, w), "{:.3f}".format
    ro_, ri, h = g["ro"], g["ri"], g["h"]
    tx, ty, leg, run = g["tx"], g["ty"], g["leg"], g["run"]

    def pt(x, y):
        return f"{f(cx + x)} {f(cy + y)}"
    ra, rb = f(ro_), f(ri)
    top = (f"M{pt(-ro_, 0)}A{ra} {ra} 0 0 1 {pt(ro_, 0)}L{pt(ri, 0)}"
           f"A{rb} {rb} 0 0 0 {pt(-ri, 0)}Z")
    bar = (f"M{pt(-g['r'], -h)}H{f(cx + g['xo'])}A{ra} {ra} 0 0 1 {pt(g['xo'], h)}"
           f"H{f(cx - g['r'])}Z")
    # The lower arc, the straight run, and (below) the arrowhead.
    ox, oy, ix, iy = ro_ * C, ro_ * C, ri * C, ri * C
    arc = (f"M{pt(ox + run * C, oy - run * C)}L{pt(ox, oy)}A{ra} {ra} 0 0 1 {pt(-ro_, 0)}"
           f"L{pt(-ri, 0)}A{rb} {rb} 0 0 0 {pt(ix, iy)}L{pt(ix + run * C, iy - run * C)}Z")
    head = (f"M{pt(tx - leg, ty - h)}H{f(cx + tx + h)}V{f(cy + ty + leg)}H{f(cx + tx - h)}"
            f"V{f(cy + ty + h)}H{f(cx + tx - leg)}Z")
    return top + bar + arc + head


# ---- the menu bar symbols ---------------------------------------------------------
CAP = 70.459              # Capline-S to Baseline-S in the SF Symbols template
CENTRE = -CAP / 2         # the cap box's optical centre, relative to the baseline
SIZE = 100.0              # the mark's box at Medium scale, matched to system glyphs
BOX = 124.0               # advance width: the mark plus its side bearing
# Stroke per weight, at SF Symbols' own line weights rather than the icon's 21%.
WEIGHTS = {"Ultralight": (2.75, 510.128), "Regular": (8.75, 1399.97), "Black": (17.75, 2881.45)}
SCALES = {"S": (696.0, 0.80), "M": (1126.0, 1.0), "L": (1556.0, 1.12)}
SYMBOLS = {"encore.mark": 1.0, "encore.mark.fill": 1.45}


def template(name, boost):
    cls = (".defaults {-sfsymbols-draw-reverses-motion-groups:false}\n\n"
           f".monochrome-0 {{-sfsymbols-motion-group:0;-sfsymbols-layer-tags:{name}}}\n\n"
           f".multicolor-0:tintColor {{-sfsymbols-motion-group:0;-sfsymbols-layer-tags:{name}}}\n\n"
           f".hierarchical-0:primary {{-sfsymbols-motion-group:0;-sfsymbols-layer-tags:{name}}}\n\n"
           ".SFSymbolsPreviewWireframe {fill:none;opacity:1.0;stroke:black;stroke-width:0.5}\n")
    guides, symbols = [], []
    for scale, (baseline, factor) in SCALES.items():
        size = SIZE * factor
        guides.append(
            f'  <line id="Baseline-{scale}" style="fill:none;stroke:#27AAE1;opacity:1;'
            f'stroke-width:0.5;" x1="263" x2="3036" y1="{baseline}" y2="{baseline}"/>\n'
            f'  <line id="Capline-{scale}" style="fill:none;stroke:#27AAE1;opacity:1;'
            f'stroke-width:0.5;" x1="263" x2="3036" y1="{baseline - CAP}" y2="{baseline - CAP}"/>')
        for wname, (weight, left) in WEIGHTS.items():
            # Capped so the counter always stays open.
            stroke = min(weight * boost, SIZE / 4.5) * factor
            d = outline(BOX * factor / 2, CENTRE, size / 2, stroke)
            symbols.append(
                f'  <g id="{wname}-{scale}" transform="matrix(1 0 0 1 {left} {baseline})">\n'
                f'   <path class="monochrome-0 multicolor-0:tintColor hierarchical-0:primary '
                f'SFSymbolsPreviewWireframe" d="{d}"/>\n  </g>')
            for side, x in (("left", left), ("right", left + BOX * factor)):
                guides.append(
                    f'  <line id="{side}-margin-{wname}-{scale}" style="fill:none;stroke:#00AEEF;'
                    f'stroke-width:0.5;opacity:1.0;" x1="{x}" x2="{x}" '
                    f'y1="{baseline - 95.215}" y2="{baseline + 24.121}"/>')
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<svg version="1.1" xmlns="http://www.w3.org/2000/svg" '
            'xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="0 0 3300 2200">\n'
            f' <!--symbol: "{name}", point size: 100.0-->\n'
            f' <style>{cls}</style>\n'
            ' <g id="Notes">\n'
            '  <rect height="2200" id="artboard" style="fill:white;opacity:1" width="3300" x="0" y="0"/>\n'
            ' </g>\n <g id="Guides">\n' + "\n".join(guides) + "\n </g>\n"
            ' <g id="Symbols">\n' + "\n".join(symbols) + "\n </g>\n</svg>\n")


def main(root):
    art = root / "Resources" / "AppIcon.icon" / "Assets" / "mark.svg"
    art.write_text(icon_svg())
    print(f"Wrote {art.relative_to(root)}")

    catalog = root / "Resources" / "Assets.xcassets"
    catalog.mkdir(parents=True, exist_ok=True)
    (catalog / "Contents.json").write_text(
        json.dumps({"info": {"author": "xcode", "version": 1}}, indent=2) + "\n")
    for name, boost in SYMBOLS.items():
        folder = catalog / f"{name}.symbolset"
        folder.mkdir(exist_ok=True)
        (folder / f"{name}.svg").write_text(template(name, boost))
        (folder / "Contents.json").write_text(json.dumps(
            {"info": {"author": "xcode", "version": 1},
             "symbols": [{"filename": f"{name}.svg", "idiom": "universal"}]}, indent=2) + "\n")
        print(f"Wrote {folder.relative_to(root)}")


if __name__ == "__main__":
    main(pathlib.Path(sys.argv[1]) if len(sys.argv) > 1
         else pathlib.Path(__file__).resolve().parent.parent)
